import {readFile,writeFile} from 'node:fs/promises';
const rpc=(await readFile('src/shared/rpc.js','utf8')).replace(/^export /gm,'');
const page=(await readFile('src/client/page.js','utf8')).replace(/^export /gm,'');
const icons={};
for(const [brand,ext] of Object.entries({chrome:'svg',edge:'png',brave:'svg',firefox:'svg'})) icons[brand]=`data:image/${ext==='svg'?'svg+xml':ext};base64,${(await readFile(`src/client/assets/${brand}.${ext}`)).toString('base64')}`;
const output=`// Generated by scripts/build.mjs; edit src/client/page.js or src/shared/rpc.js.\nwindow.__ModuleLoader__.load({id:'@local/dsh-browser-flock',factory(require){
const React=require('react');
${rpc}
${page}
const browserIcons=${JSON.stringify(icons)};
return {inject:['slots','locale','remote'],async apply(ctx){
await ctx.remote.$mount(remoteContribution);
ctx.inject(['remote.browserFlock'],ctx=>{
const Page=createPage(React,ctx,browserIcons);
const label=()=>ctx.locale.bind('browser-flock')('title');
function Icon({size=20}){return React.createElement('svg',{width:size,height:size,viewBox:'0 0 24 24',fill:'none',stroke:'currentColor',strokeWidth:1.7},React.createElement('rect',{x:3,y:4,width:15,height:12,rx:2}),React.createElement('rect',{x:7,y:8,width:14,height:12,rx:2}),React.createElement('path',{d:'M7 12h14'}));}
ctx.slots.inject('sidebar.panellist',()=>ctx.slots.register({name:'sidebar.panellist',id:'browser-flock',order:20,label},Icon));
ctx.slots.inject('main',()=>ctx.slots.register({name:'main',key:'browser-flock'},Page));
});
}};
}});\n`;
await writeFile('client.js',output);
console.log(`Built client.js (${Buffer.byteLength(output)} bytes).`);
