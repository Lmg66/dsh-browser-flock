test('proxy validation and Chromium flags',()=>{
  assert.deepEqual(proxyArguments(),[]);assert.deepEqual(proxyArguments({mode:'direct'}),['--no-proxy-server']);
  assert.deepEqual(proxyArguments({mode:'socks5',host:'[::1]',port:1080}),['--proxy-server=socks5://[::1]:1080']);
  assert.deepEqual(proxyArguments({mode:'http',host:'LOCALHOST',port:8080}),['--proxy-server=http://localhost:8080']);
  for(const host of ['a@b','http://host','host/path','host:8080','[example.com]','a b','-bad']) assert.throws(()=>proxyConfig({mode:'http',host,port:80}));
  assert.throws(()=>proxyConfig({mode:'http',host:'host',port:0}));
  assert.throws(()=>proxyConfig({mode:'direct',host:'host'}));
  assert.throws(()=>openInput({runtime_id:'x',proxy:{mode:'direct'},proxy_preset_id:'y'}));
  assert.throws(()=>openInput({instance_id:'x',proxy:{mode:'direct'}}));
});
test('Firefox preserves preferences and resets stale modes without certificate changes',async t=>{
  const root=await fs.mkdtemp(path.join(os.tmpdir(),'flock-proxy-'));t.after(()=>fs.rm(root,{recursive:true,force:true}));
  const file=path.join(root,'user.js');await fs.writeFile(file,'user_pref("custom.pref", true);\n');
  await prepareFirefoxProxy(root,{mode:'http',host:'localhost',port:8080});
  let text=await fs.readFile(file,'utf8');assert.match(text,/network.proxy.ssl_port", 8080/);
  await prepareFirefoxProxy(root,{mode:'socks5',host:'localhost',port:1080});
  text=await fs.readFile(file,'utf8');assert.match(text,/network.proxy.http_port", 0/);assert.match(text,/network.proxy.socks_remote_dns", true/);
  await prepareFirefoxProxy(root,{mode:'system'});text=await fs.readFile(file,'utf8');
  assert.match(text,/custom.pref/);assert.match(text,/network.proxy.type", 5/);assert.match(text,/network.proxy.socks_port", 0/);
  assert.equal(text.split('BEGIN Browser Flock').length,2);assert.doesNotMatch(text,/enterprise_roots|cert/);
});
test('presets persist and instances copy settings; replay survives preset deletion',async t=>{
  const root=await fs.mkdtemp(path.join(os.tmpdir(),'flock-proxy-state-'));const repo=new Repository(root);
  t.after(async()=>{await repo.close();await fs.rm(root,{recursive:true,force:true});});await repo.open();
  const runtime={id:'r',browser:'chrome',available:true};const launches=[];
  const runtimes={get:()=>runtime,freshness:()=>({})};
  const platform={launch:async(r,p,u,o)=>{launches.push(o);return {processIdentity:{pid:123,startTime:'fake'}}},inspectInstance:async()=>({status:'stopped'})};
  const instances=new InstanceManager(repo,runtimes,platform);const ops=new Operations(repo,runtimes,instances);
  const registered=new Map();applyTools({tools:{register:tool=>registered.set(tool.name,tool)},sandboxPolicy:{resolve:()=>({mode:'danger-full-access'})},browserFlock:ops,get:()=>undefined});
  const call=async(action,args)=>JSON.parse(await registered.get(action).execute(args,{signal:new AbortController().signal,callId:'test'}));
  const created=await call('save_browser_proxy_preset',{name:'Local',proxy:{mode:'http',host:'localhost',port:8080}});assert.equal(created.ok,true);
  const id=created.data.id;const request={runtime_id:'r',proxy_preset_id:id,request_id:'retry'};
  const opened=await instances.open(request);assert.equal(opened.instance.proxy.port,8080);
  await call('save_browser_proxy_preset',{preset_id:id,name:'Changed',proxy:{mode:'socks5',host:'localhost',port:1080}});
  assert.equal(instances.get(opened.instance.id).proxy.port,8080);
  await repo.close();await repo.open();assert.equal(repo.snapshot().proxyPresets[0].proxy.port,1080);
  assert.equal((await call('list_browser_proxy_presets',{})).data.total,1);
  assert.equal(ops.snapshot().proxy_presets.length,1);
  await call('delete_browser_proxy_preset',{preset_id:id});assert.equal((await instances.open(request)).replayed,true);
  await instances.open({instance_id:opened.instance.id});assert.equal(launches.at(-1).proxy.port,8080);
  await assert.rejects(call('save_browser_proxy_preset',{name:'bad',proxy:{mode:'system'}}),{code:'INVALID_ARGS'});
  await assert.rejects(instances.open({runtime_id:'r',proxy_preset_id:id}),{code:'PROXY_PRESET_NOT_FOUND'});
});
